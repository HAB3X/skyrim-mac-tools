/* fxc.exe stand-in for cross builds on macOS (run through Wine): compiles one HLSL entry point with Microsoft's
 * d3dcompiler_47.dll and writes a /Fh header in fxc's format (const BYTE <name>[] = { ... };).
 * Supports what DirectXTK's CompileShaders.cmd passes:
 *   <file> /T<profile> /E<entry> /Fh<out.inc> /Vn<name> [/Fd<pdb>] /nologo /WX /Ges /Zi /Zpc /Zpr /Qstrip_reflect /Qstrip_debug
 * /Fd and /Zi are accepted and ignored (the shaders are stripped of debug data anyway).
 * Build: ~/Developer/xwin/fxc/build.sh */
#include <windows.h>
#include <d3dcompiler.h>
#include <stdio.h>
#include <string.h>

static int usage(const char *msg)
{
    fprintf(stderr, "fxc: %s\n", msg);
    return 2;
}

static int has_prefix(const char *s, const char *p)
{
    return _strnicmp(s, p, strlen(p)) == 0 && (s[0] == '/' || s[0] == '-');
}

int main(int argc, char **argv)
{
    const char *input = NULL, *profile = NULL, *entry = "main", *outInc = NULL, *varName = NULL;
    UINT flags = 0, stripFlags = 0;

    for (int i = 1; i < argc; ++i) {
        const char *a = argv[i];
        if (a[0] != '/' && a[0] != '-') { input = a; continue; }
        if (has_prefix(a, "/T"))               profile = a + 2;
        else if (has_prefix(a, "/E"))          entry = a + 2;
        else if (has_prefix(a, "/Fh"))         outInc = a + 3;
        else if (has_prefix(a, "/Vn"))         varName = a + 3;
        else if (has_prefix(a, "/Fd") || !_stricmp(a + 1, "nologo") || !_stricmp(a + 1, "Zi")) { }
        else if (!_stricmp(a + 1, "WX"))       flags |= D3DCOMPILE_WARNINGS_ARE_ERRORS;
        else if (!_stricmp(a + 1, "Ges"))      flags |= D3DCOMPILE_ENABLE_STRICTNESS;
        else if (!_stricmp(a + 1, "Zpc"))      flags |= D3DCOMPILE_PACK_MATRIX_COLUMN_MAJOR;
        else if (!_stricmp(a + 1, "Zpr"))      flags |= D3DCOMPILE_PACK_MATRIX_ROW_MAJOR;
        else if (!_stricmp(a + 1, "Qstrip_reflect")) stripFlags |= D3DCOMPILER_STRIP_REFLECTION_DATA;
        else if (!_stricmp(a + 1, "Qstrip_debug"))   stripFlags |= D3DCOMPILER_STRIP_DEBUG_INFO;
        else { fprintf(stderr, "fxc: unsupported option %s\n", a); return 2; }
    }
    if (!input || !profile || !outInc || !varName)
        return usage("need <file> /T<profile> /Fh<out> /Vn<name>");

    wchar_t winput[MAX_PATH];
    MultiByteToWideChar(CP_UTF8, 0, input, -1, winput, MAX_PATH);

    ID3DBlob *code = NULL, *errors = NULL;
    HRESULT hr = D3DCompileFromFile(winput, NULL, D3D_COMPILE_STANDARD_FILE_INCLUDE, entry, profile, flags, 0, &code, &errors);
    if (errors) {
        fprintf(stderr, "%.*s", (int)errors->lpVtbl->GetBufferSize(errors), (const char *)errors->lpVtbl->GetBufferPointer(errors));
        errors->lpVtbl->Release(errors);
    }
    if (FAILED(hr)) {
        fprintf(stderr, "fxc: compiling %s (%s, %s) failed: 0x%08lx\n", input, entry, profile, (unsigned long)hr);
        return 1;
    }

    ID3DBlob *out = code;
    if (stripFlags) {
        ID3DBlob *stripped = NULL;
        if (FAILED(D3DStripShader(code->lpVtbl->GetBufferPointer(code), code->lpVtbl->GetBufferSize(code), stripFlags, &stripped)))
            return usage("D3DStripShader failed");
        code->lpVtbl->Release(code);
        out = stripped;
    }

    FILE *f = fopen(outInc, "w");
    if (!f) { fprintf(stderr, "fxc: cannot write %s\n", outInc); return 1; }
    const unsigned char *p = (const unsigned char *)out->lpVtbl->GetBufferPointer(out);
    size_t n = out->lpVtbl->GetBufferSize(out);
    fprintf(f, "#if 0\n//\n// Generated by fxc stand-in (d3dcompiler_47) - %s %s\n//\n#endif\n\nconst BYTE %s[] =\n{\n", profile, entry, varName);
    for (size_t i = 0; i < n; ++i)
        fprintf(f, "%s%3u%s", (i % 16 == 0) ? "    " : "", p[i], (i + 1 == n) ? "\n" : ((i % 16 == 15) ? ",\n" : ", "));
    fprintf(f, "};\n");
    fclose(f);
    out->lpVtbl->Release(out);
    printf("compilation header save succeeded; see %s\n", outInc);
    return 0;
}
